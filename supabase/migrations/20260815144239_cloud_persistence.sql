    revoke all on table public.semesters from anon, authenticated;
  end if;
  if to_regclass('public.courses') is not null then
    revoke all on table public.courses from anon, authenticated;
  end if;
  if to_regclass('public.assignments') is not null then
    revoke all on table public.assignments from anon, authenticated;
  end if;
  if to_regclass('public.user_settings') is not null then
    revoke all on table public.user_settings from anon, authenticated;
  end if;
end $$;
revoke all on table public.legacy_local_backups from anon, authenticated;
